  const tierBump = (r[idx('tier_bump_candidate')] || '').trim().toLowerCase() === 'yes';
  const notes = (r[idx('notes')] || '').trim();
  const activeMatch = notes.match(/active_pages=(\d+)\s+of\s+(\d+)/);
  const activePages = activeMatch ? parseInt(activeMatch[1], 10) : null;
  const thresholdMatch = notes.match(/bump threshold (\d+)/);
