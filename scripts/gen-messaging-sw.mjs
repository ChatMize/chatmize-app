/**
 * Prebuild step: generates public/firebase-messaging-sw.js with the Firebase
 * config baked in (a service worker cannot read Vite env vars at runtime).
 *
 * Env vars (VITE_FIREBASE_*) take precedence, falling back to
 * firebase-applet-config.json — same resolution as src/lib/firebase.ts.
 */
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const env = process.env;

let applet = {};
try {
  applet = JSON.parse(readFileSync(join(root, "firebase-applet-config.json"), "utf8"));
} catch { /* optional */ }

const pick = (envKey, appletKey) => env[envKey] || applet[appletKey] || "";
const config = {
  apiKey: pick("VITE_FIREBASE_API_KEY", "apiKey"),
  authDomain: pick("VITE_FIREBASE_AUTH_DOMAIN", "authDomain"),
  projectId: pick("VITE_FIREBASE_PROJECT_ID", "projectId"),
  storageBucket: pick("VITE_FIREBASE_STORAGE_BUCKET", "storageBucket"),
  messagingSenderId: pick("VITE_FIREBASE_MESSAGING_SENDER_ID", "messagingSenderId"),
  appId: pick("VITE_FIREBASE_APP_ID", "appId"),
};
const region = "us-west2";

const sw = `/* Auto-generated by scripts/gen-messaging-sw.mjs. Do not edit by hand. */
importScripts("https://www.gstatic.com/firebasejs/12.19.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/12.19.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config, null, 2)});
const messaging = firebase.messaging();

function trackEvent(workspaceId, event) {
  if (!workspaceId) return;
  try {
    // Unauthenticated callable invocation (callable wire protocol).
    fetch("https://${region}-${config.projectId}.cloudfunctions.net/trackPushEvent", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ data: { workspaceId, event } }),
      keepalive: true,
    }).catch(() => {});
  } catch (e) { /* best effort */ }
}

messaging.onBackgroundMessage((payload) => {
  const data = payload.data || {};
  const title = (payload.notification && payload.notification.title) || "New update";
  const body = (payload.notification && payload.notification.body) || "";
  const link = data.link || (payload.webpush && payload.webpush.fcmOptions && payload.webpush.fcmOptions.link) || "/";
  const image = payload.notification && payload.notification.image;
  const options = {
    body,
    icon: "/chatmize-head.png",
    badge: "/chatmize-head.png",
    data: { link, workspaceId: data.workspaceId || "" },
  };
  if (image) options.image = image;
  trackEvent(data.workspaceId, "delivered");
  self.registration.showNotification(title, options);
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const link = (event.notification.data && event.notification.data.link) || "/";
  const workspaceId = event.notification.data && event.notification.data.workspaceId;
  trackEvent(workspaceId, "clicked");
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ("focus" in client) { client.focus(); break; }
      }
      return clients.openWindow(link);
    })
  );
});
`;

mkdirSync(join(root, "public"), { recursive: true });
writeFileSync(join(root, "public", "firebase-messaging-sw.js"), sw);
console.log("firebase-messaging-sw.js generated for project", config.projectId || "(no project configured)");
